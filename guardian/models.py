"""
It defines the data models used in the Guardian project, 
including Verdict, Layer, Risk, Finding, Result, and Action classes. 
These models represent the outcomes of analyzing code
for security risks and errors. 
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum, IntEnum


class Verdict(IntEnum):
    """ 
    Represents the possible verdicts
    for an action analysis. So it can be
    ALLOW, CONFIRM, BLOCK, or ERROR.
    """
    ALLOW = 0
    CONFIRM = 1
    BLOCK = 2
    ERROR = 3


class Layer(Enum):
    """ 
    It is the stage of analysis that basicallly 
    foyund the error or risk.
    It can be LEXICAL, SYNTAX, or SEMANTIC.
    """
    LEXICAL = "Lexical error"
    SYNTAX = "Syntax error"
    SEMANTIC = "Semantic risk"


class Risk(IntEnum):
    """ 
    Represents the level of risk. 
    It can be NONE, MEDIUM, or HIGH. This one 
    is only for the URL rules.
    """
    NONE = 0
    MEDIUM = 1
    HIGH = 2


@dataclass
class Finding:
    """ 
    Represents a finding in the analysis of an action.
    
    This it is important to follow, because is the format 
    that each finding in the syntax, 
    semantic or lexical analysis will be reported.
    
    Example:
    Finding(Layer.SYNTAX, "expected FROM after the column list")
    Finding(Layer.SEMANTIC, "DELETE without WHERE", rule="R1", verdict=Verdict.BLOCK)
    Finding(Layer.SEMANTIC, "http scheme", rule="R7", risk=Risk.MEDIUM)
    """
    layer: Layer
    message: str
    rule: str | None = None
    verdict: Verdict | None = None
    risk: Risk | None = None


@dataclass
class Result:
    """ 
    Result is what every analyzer returns. 
    
    The properties are:
    
    tree: The parse tree generated by the analyzer, otherwise None. 
    findings: A list of Finding objects representing the issues found during analysis.
    ok: TRUE only if there is a tree and no lexical or syntax error. 
    
    Ok it is important because it is the 
    property that the main program uses to 
    decide if the action is valid or not, and continue to the next stage.
    
    """
    tree: object | None
    
    findings: list[Finding] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.tree is not None and not any(
            f.layer in (Layer.LEXICAL, Layer.SYNTAX) for f in self.findings
        )


@dataclass
class Action: 
    
    line: int
    text: str
    mode: str
    origin: str | None = None
    tool: str | None = None
    argument: str | None = None
    tree: object | None = None
    findings: list[Finding] = field(default_factory=list)
    verdict: Verdict | None = None
